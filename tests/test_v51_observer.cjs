'use strict';
const assert=require('node:assert/strict');
const THI=require('../download_observer.js');
const secret='XxPRIVATE_AUTH_TOKEN_84Xx',sign='XxSIGNATURE_ONLY_98Xx';
const url='https://media.example/download/file?X-Amz-Signature='+sign+'&X-Amz-Expires=120&access_token='+secret;
const raw={tabId:4,requestId:'req-22',timeStamp:Date.now(),method:'POST',type:'xmlhttprequest',url,
 requestBody:{formData:{assetId:['A100'],rendition:['original'],password:[secret],signature:[sign]}}};
const before=THI.classify('request',raw);
assert.equal(before.method,'POST');assert(before.fieldCategories.includes('asset ID'));
assert(before.fieldCategories.includes('other field'));
assert(before.signedIndicators.includes('URL signing fields'));
const head=THI.classify('headers',{...raw,requestHeaders:[{name:'Authorization',value:secret},{name:'x-api-key',value:sign},{name:'X-Amz-Date',value:'20261024'}]});
assert(head.headerIndicators.includes('Authorization header present'));
assert(head.headerIndicators.includes('API key header present'));
const redirect=THI.classify('redirect',{...raw,redirectUrl:'https://cdn.example/signed/'+secret+'?token='+sign,statusCode:302});
assert.equal(redirect.redirectHost,'cdn.example');
const end=THI.classify('complete',{...raw,statusCode:200,responseHeaders:[{name:'Content-Disposition',value:'attachment; filename="'+secret+'.jpg"'},{name:'Content-Type',value:'image/jpeg'}]});
assert.equal(end.attachment,true);
const candidate=THI.download('created',{id:17,referrer:'https://gallery.example/view?token='+secret,finalUrl:url,filename:'C:/'+secret+'.jpg'});
assert.equal(candidate.referrerHost,'gallery.example');
const rows=THI.summaries([before,head,redirect,end,candidate]);
assert.equal(rows[0].length,undefined);
assert(rows.some(r=>r.method==='POST'&&r.redirect==='cdn.example'&&r.status==='200'));
assert(rows.some(r=>r.method==='DOWNLOAD'&&r.evidence.includes('Referrer-origin')));
const stored=JSON.stringify({before,head,redirect,end,candidate,rows});
for(const forbidden of [secret,sign,'password','C:/','signed/'+secret,'filename='])assert(!stored.includes(forbidden),'leak: '+forbidden);
const opaque=THI.classify('request',{...raw,requestBody:{raw:[{bytes:new Uint8Array([1,2])}]}});
assert.equal(opaque.bodyState,'opaque body not inspected');
assert(!JSON.stringify(opaque).includes('bytes'));
assert.equal(THI.classify('request',{...raw,method:'GET',url:'https://assets.example/other'}),null);
console.log('PASS v5.1 pure request, header, redirect, download classification and no credential values');
