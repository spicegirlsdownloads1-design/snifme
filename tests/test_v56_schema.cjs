'use strict';
const assert=require('node:assert/strict');
const U=require('../upload_api_intel.js');
const secret='SECRET_QUESTIONABLE_FIELD_7338';
const base='https://dam.example/api/assets/123?token='+secret;
const shape=(fields,url=base)=>({url,host:'dam.example',method:'GET',mime:'application/json',fields:fields.map(([path,type])=>({path,type}))});
const before={origin:'https://dam.example',responses:[shape([['assetId','string'],['meta','object'],['meta.width','number'],['emailAddress','string'],[secret,'string']])],sessionId:'private'+secret};
const after={origin:'https://dam.example',responses:[shape([['assetId','string'],['meta','object'],['meta.width','string'],['meta.height','number'],['authentication','object']])],sessionId:'secret'+secret};
let output=U.compare(before,after);
assert.equal(output.rows.length,1);assert.equal(output.rows[0].typeChanges,1);assert.equal(output.rows[0].added,1);
assert.equal(output.rows[0].removed,0);assert.equal(output.totals.changedShapes,1);
assert(!JSON.stringify(output).includes(secret));assert(!JSON.stringify(output).includes('/api/assets/'));
assert(!JSON.stringify(output).includes('authentication'));
assert.equal(U.compare({origin:'https://first.example',responses:[]},{origin:'https://second.example',responses:[]}).error,'Choose captures of the same exact origin.');
let missing=U.compare(before,{origin:before.origin,responses:[]});assert.equal(missing.totals.notObserved,1);
let newOnly=U.compare({origin:before.origin,responses:[]},after);assert.equal(newOnly.totals.newlyObserved,1);
let poisoned=U.compare({origin:'https://dam.example',responses:[shape([[secret,'string']],'https://dam.example/private/'+secret)]},after);
assert(!JSON.stringify(poisoned).includes(secret));
console.log('PASS v5.6 API schema diff: added/type/removed count, absent sightings, origin isolation, opaque exports');
