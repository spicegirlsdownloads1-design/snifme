'use strict';
const assert=require('node:assert/strict');
const S=require('../security_intelligence.js');
const Vault=require('../evidence_vault.js');
const token='SECRET_SYNTHETIC_123456789_NON_WORKING';
const base={url:'https://api.example.invalid/api/users/ABCDEFGHSECRET',method:'GET',requestId:'1234',timeStamp:1794012000000,statusCode:200,initiator:'https://app.example.invalid'};
const test=(stage,overrides={})=>S.classify(stage,{...base,...overrides});
const ids=rows=>rows.map(x=>x.ruleId);
assert(ids(test('request',{url:base.url+'?access_token='+token})).includes('SECRET_QUERY'));
assert.equal(test('request',{url:base.url+'?token=demo'}).length,0);
assert(!ids(test('request',{url:base.url+'?expires=3600'})).includes('SIGNED_URL_WINDOW'));
const signed=test('request',{url:'https://cdn.example.invalid/media/a.png?X-Amz-Signature='+token+'&X-Amz-Expires=3600'});
assert.equal(signed.find(x=>x.ruleId==='SIGNED_URL_WINDOW').classification,'aws-v4');
assert.equal(signed.find(x=>x.ruleId==='SIGNED_URL_WINDOW').declaration,'15m-to-1h');
assert(ids(test('request',{url:base.url+'?session_id='+token})).includes('SESSION_QUERY'));
assert.equal(test('request',{method:'POST',url:'https://app.example.invalid/api/admin/users'}).find(x=>x.ruleId==='MUTATION_CONTEXT').method,'POST');
assert(!ids(test('request',{method:'GET',url:'https://app.example.invalid/api/admin/users'})).includes('MUTATION_CONTEXT'));
const sensitiveForm=test('request',{url:'https://app.example.invalid/api/upload',method:'POST',requestBody:{formData:{client_secret:['PRIVATE_DO_NOT_KEEP'],file:['binary'],csrf_token:['ALSO_PRIVATE']}}});
assert(ids(sensitiveForm).includes('FORM_FIELD_CONTEXT'));
assert(sensitiveForm.find(x=>x.ruleId==='FORM_FIELD_CONTEXT').markers.includes('csrf-field-present'));
assert(!JSON.stringify(sensitiveForm).includes('PRIVATE_DO_NOT_KEEP'));
assert(!JSON.stringify(sensitiveForm).includes('ALSO_PRIVATE'));
const normalCors=test('response-headers',{responseHeaders:[{name:'Access-Control-Allow-Origin',value:'*'}]});
assert(!ids(normalCors).includes('CORS_WILDCARD_CREDENTIALS'));
const badCors=test('response-headers',{responseHeaders:[{name:'Access-Control-Allow-Origin',value:'*'},{name:'Access-Control-Allow-Credentials',value:'true'}]});
assert(ids(badCors).includes('CORS_WILDCARD_CREDENTIALS'));
assert(badCors[0].limitation.includes('Browsers reject'));
const restrictedCors=test('response-headers',{responseHeaders:[{name:'Access-Control-Allow-Origin',value:'https://app.example.invalid'},{name:'Access-Control-Allow-Credentials',value:'true'}]});
assert(ids(restrictedCors).includes('CORS_CREDENTIAL_SCOPE'));
assert(restrictedCors[0].limitation.includes('does not prove arbitrary origin reflection'));
assert(ids(test('response-headers',{responseHeaders:[{name:'Access-Control-Allow-Origin',value:'null'},{name:'Access-Control-Allow-Credentials',value:'true'}]})).includes('CORS_NULL_ORIGIN'));
const redirect=test('redirect',{redirectUrl:'https://idp.example.invalid/callback?code='+token});
assert(ids(redirect).includes('OAUTH_REDIRECT_DATA'));
assert(!ids(test('redirect',{redirectUrl:'https://api.example.invalid/callback?code='+token})).includes('OAUTH_REDIRECT_DATA'));
const referer=test('request-headers',{requestHeaders:[{name:'Referer',value:'https://app.example.invalid/photos?access_token='+token}]});
assert(ids(referer).includes('REFERER_SECRET'));
assert(!ids(test('request-headers',{url:'https://app.example.invalid/resource',requestHeaders:[{name:'Referer',value:'https://app.example.invalid/?access_token='+token}]})).includes('REFERER_SECRET'));
const cookie=test('response-headers',{responseHeaders:[{name:'Set-Cookie',value:'auth_session='+token+'; Path=/; SameSite=None'}]});
assert(ids(cookie).includes('COOKIE_FLAGS'));
assert(!ids(test('response-headers',{responseHeaders:[{name:'Set-Cookie',value:'auth_session='+token+'; Secure; HttpOnly; SameSite=Lax'}]})).includes('COOKIE_FLAGS'));
const azure=test('request',{url:'https://blob.example.invalid/archive/image.jpg?sig='+token+'&se=2026-11-08T01%3A00%3A00Z'});
assert.equal(azure.find(x=>x.ruleId==='SIGNED_URL_WINDOW').declaration,'expiry-timestamp-present');
const all=[...signed,...badCors,...restrictedCors,...redirect,...referer,...cookie,...azure,...test('request',{url:base.url+'?access_token='+token})];
const serialized=JSON.stringify(all);
assert(!serialized.includes(token),'raw credential must never be stored in security findings');
assert(!serialized.includes('ABCDEFGHSECRET'),'unknown path segments must not leak into safe route');
assert(!serialized.includes('auth_session='),'raw cookies must never be stored');
assert(!serialized.includes('redirectUrl'),'raw redirect URL must not be persisted');
assert(all.every(x=>!/(?:vulnerable|exploitable|CVE-\d)/i.test(x.title)));
assert(all.every(x=>typeof x.route==='string' && !x.route.includes('SECRET')));
const har={log:{entries:[
 {startedDateTime:'2026-11-07T01:00:00.000Z',request:{url:'https://a.example.invalid/api?access_token='+token,method:'GET',headers:[]},response:{status:200,headers:[]}},
 {startedDateTime:'2026-11-07T01:00:01.000Z',request:{url:'https://a.example.invalid/auth/reset',method:'POST',headers:[{name:'Authorization',value:'Bearer '+token}]},response:{status:302,redirectURL:'https://idp.example.invalid/callback?code='+token,headers:[]}}
]}};
const analyzed=S.analyzeHar(JSON.stringify(har));
assert(analyzed.ok);assert.equal(analyzed.reviewed,2);
assert(ids(analyzed.observations).includes('SECRET_QUERY'));
assert(ids(analyzed.observations).includes('OAUTH_REDIRECT_DATA'));
assert(ids(analyzed.observations).includes('MUTATION_CONTEXT'));
assert(!JSON.stringify(analyzed).includes(token),'HAR raw values may not escape analysis');
assert.equal(S.analyzeHar('{not json').ok,false);
assert.equal(S.analyzeHar({log:{entries:[]}}).reviewed,0);
const record={origin:'https://a.example.invalid',createdAt:'2026-11-07T01:00:00.000Z',securityObservations:all,securityObservationsDropped:3};
const imported=Vault.sanitizeImport({format:'trufflehog-vault-session',version:1,record},(v)=>{try{const x=new URL(v);return x.origin+x.pathname;}catch{return '';}});
assert.equal(imported.securityObservations.length,all.length);
assert.equal(imported.securityObservationsDropped,3);
assert.equal(imported.schema,21);
assert(!JSON.stringify(imported).includes(token));
const file=require('node:fs').readFileSync(require('node:path').join(__dirname,'../background.js'),'utf8');
for(const stage of ['request','request-headers','response-headers','redirect'])assert(file.includes(`recordSecurityStage('${stage}'`));
const manifest=require('../manifest.json');assert.equal(manifest.version,'7.19.0');
assert(!manifest.permissions.includes('debugger'),'deep inspection must not be silently enabled');
console.log('PASS v7.18 security rules, provenance, negative fixtures, privacy, HAR offline and import round trip');
